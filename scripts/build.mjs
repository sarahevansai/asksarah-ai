#!/usr/bin/env node
// askSarah.ai v2 build. Zero dependencies.
//
//   node scripts/build.mjs            build published content
//   DRAFTS=1 node scripts/build.mjs   also render drafts (local preview only, never commit)
//
// Reads content/**, writes static HTML next to the existing hand-built pages,
// plus search-index.json and sitemap.xml. Existing pages are never touched
// except index.html (the homepage), which this script owns.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { header, footer, FONTS } from './chrome.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://asksarah.ai';
const SUBSCRIBE_URL = 'https://prsarahevans.substack.com/subscribe';
const DRAFTS = process.env.DRAFTS === '1';
const GENERATED = '<!-- Generated by scripts/build.mjs from content/. Edit the content files, not this page. -->';

// ---------- load ----------
const readJSON = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
function loadDir(dir) {
  const full = path.join(ROOT, 'content', dir);
  if (!fs.existsSync(full)) return [];
  return fs.readdirSync(full)
    .filter((f) => f.endsWith('.json') && !f.startsWith('_'))
    .map((f) => ({ ...readJSON(path.join(full, f)), _file: `content/${dir}/${f}` }))
    .filter((x) => x.published !== false || DRAFTS);
}
const C = {
  skill: loadDir('skills'),
  pack: loadDir('packs'),
  stack: loadDir('stack'),
  'ai-use': loadDir('ai-uses'),
  shortcut: loadDir('shortcuts'),
  system: loadDir('systems'),
  edit: loadDir('edit'),
};
const articles = readJSON(path.join(ROOT, 'content', 'articles.json'));

// ---------- validation ----------
const errors = [];
const checkoutSrc = fs.readFileSync(path.join(ROOT, 'api', 'create-checkout.js'), 'utf8');
const stripePrices = {};
for (const m of checkoutSrc.matchAll(/'([a-z0-9-]+)':\s*\{\s*name:\s*'[^']*',\s*priceInCents:\s*(\d+)/g)) stripePrices[m[1]] = Number(m[2]);
for (const s of C.skill) {
  if (!s.slug || !s.title) errors.push(`${s._file}: needs slug and title`);
  if (s.free_or_paid === 'paid' && s.status === 'available') {
    const id = s.stripe_id || s.slug;
    if (!(id in stripePrices)) errors.push(`${s._file}: stripe_id "${id}" isn't in api/create-checkout.js, so checkout would fail`);
    else if (Math.round(Number(s.price) * 100) !== stripePrices[id])
      errors.push(`${s._file}: price ${s.price} doesn't match api/create-checkout.js (${stripePrices[id] / 100}). Change both or neither.`);
  }
}
if (errors.length) { console.error('Build stopped:\n  ' + errors.join('\n  ')); process.exit(1); }

// ---------- helpers ----------
const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const arr = (v) => (Array.isArray(v) ? v : v ? [v] : []);
const has = (v) => (Array.isArray(v) ? v.length > 0 : v !== null && v !== undefined && String(v).trim() !== '');
const fmtPrice = (p) => (Number(p) % 1 === 0 ? `$${Number(p)}` : `$${Number(p).toFixed(2)}`);
const fmtDate = (d) => (d ? new Date(d + 'T12:00:00Z').toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC' }) : '');
const paras = (v) => arr(v).map((p) => `<p>${esc(p)}</p>`).join('\n');
const list = (v, cls = 'ticks') => (has(v) ? `<ul class="${cls}">${arr(v).map((x) => `<li>${esc(x)}</li>`).join('')}</ul>` : '');

const TYPES = {
  skill: { label: 'Skill', base: '/skills' },
  pack: { label: 'Skill Pack', base: '/skills' },
  stack: { label: "Sarah's Stack", base: '/stack' },
  'ai-use': { label: 'How I use AI', base: '/things-ai-can-do' },
  shortcut: { label: 'Shortcut', base: '/shortcuts' },
  system: { label: 'System', base: '/systems' },
  edit: { label: "Sarah's Edit", base: '/edit' },
  article: { label: 'Article', base: '' },
};
function urlFor(type, item) {
  if (type === 'pack') return `/skills#${item.slug}`; // pack pages arrive in Phase 2
  if (type === 'article') return `/${item.slug}`;
  return `${TYPES[type].base}/${item.slug}`;
}
function find(type, slug) {
  if (type === 'article') return articles.find((a) => a.slug === slug);
  return (C[type] || []).find((x) => x.slug === slug);
}
function badgeFor(type, item) {
  if (type === 'skill' || type === 'pack') {
    if (item.status === 'coming-soon') return item.free_or_paid === 'paid'
      ? { text: item.price ? `${fmtPrice(item.price)} · Coming soon` : 'Coming soon', cls: 'badge-soon' }
      : { text: 'Free · Coming soon', cls: 'badge-free' };
    return item.free_or_paid === 'paid' ? { text: fmtPrice(item.price), cls: 'badge-paid' } : { text: 'Free', cls: 'badge-free' };
  }
  if (type === 'ai-use') return { text: `#${item.number}`, cls: 'badge-new' };
  return null;
}
const summaryOf = (type, it) => it.description || it.promise || it.short_description || it.what_i_use_it_for || it.problem || it.why_i_like_it || '';
const titleOf = (it) => it.title || it.name;

function card(type, item, { showType = false, trackId = '' } = {}) {
  const b = badgeFor(type, item);
  const url = urlFor(type, item);
  return `<article class="card"${item.category ? ` data-cats="${esc(arr(item.category).join('|'))}"` : ''}>
  <div class="badges">${showType ? `<span class="badge badge-type">${esc(TYPES[type].label)}</span>` : ''}${b ? `<span class="badge ${b.cls}">${esc(b.text)}</span>` : ''}${item.new && item.status !== 'coming-soon' ? '<span class="badge badge-new">New</span>' : ''}</div>
  <h3><a href="${url}"${trackId ? ` data-track="related_click" data-track-id="${esc(trackId)}"` : ''}>${esc(titleOf(item))}</a></h3>
  <p>${esc(summaryOf(type, item))}</p>
  <div class="card-foot"><span>${esc(arr(item.category).join(' · '))}</span><span class="go" aria-hidden="true">→</span></div>
</article>`;
}

function related(item, fromId) {
  const items = arr(item.related_items)
    .map((r) => ({ type: r.type, it: find(r.type, r.slug) }))
    .filter((r) => r.it && (r.it.published !== false || DRAFTS))
    .slice(0, 4);
  if (!items.length) return '';
  return `<aside class="related" aria-labelledby="rel-h"><h2 id="rel-h">Where to go next</h2><div class="grid">${items
    .map((r) => card(r.type, r.it, { showType: true, trackId: `${fromId}->${r.type}:${r.it.slug}` }))
    .join('')}</div></aside>`;
}

