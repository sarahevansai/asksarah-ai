const crumbs = (trail) => `<nav class="crumbs" aria-label="Breadcrumb">${trail.map(([n, p], i) => (i === trail.length - 1 ? esc(n) : `<a href="${p}">${esc(n)}</a> / `)).join('')}</nav>`;

