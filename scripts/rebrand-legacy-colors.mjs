#!/usr/bin/env node
// One-time rebrand of the hand-built pages: keeps Sarah's dark style, swaps
// violet/cyan for pink/rose, and warms the purple-tinted darks to near-black.
// Safe to re-run: no target color is also a source color.
//   node scripts/rebrand-legacy-colors.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SKIP = new Set(['email-template.html', 'card.html', 'google8dc333a5d1a3e4f3.html', 'index-v2-backup.html']);

// Solid colors (case-insensitive, whole hex only).
const HEX = {
  // purple-tinted darks -> warm near-black
  '#0c0a1a': '#0d0a0c', '#110f24': '#140f13', '#16132e': '#1b141a', '#1c1838': '#241a21',
  // text
  '#f0eef8': '#f8eef3', '#c4c0d8': '#d9cbd2', '#7a758f': '#9a8a93',
  // violet -> pink, cyan -> rose
  '#7c3aed': '#db2777', '#a78bfa': '#f472b6', '#c084fc': '#f9a8d4', '#818cf8': '#f472b6',
  '#06b6d4': '#fb7185', '#22d3ee': '#fda4af', '#2dd4bf': '#fda4af',
};
// rgba(r,g,b,a) channels -> new channels, alpha kept.
const RGB = {
  '12,10,26': '13,10,12', '17,15,36': '20,15,19', '22,19,46': '27,20,26', '28,24,56': '36,26,33', '15,12,35': '16,11,15',
  '122,117,143': '154,138,147',
  '124,58,237': '219,39,119', '167,139,250': '244,114,182', '168,85,247': '236,72,153', '59,130,246': '236,72,153',
  '6,182,212': '251,113,133', '34,211,238': '253,164,175', '45,212,191': '253,164,175', '13,148,136': '219,39,119',
};

let changed = 0;
for (const f of fs.readdirSync(ROOT).filter((f) => f.endsWith('.html') && !SKIP.has(f))) {
  const full = path.join(ROOT, f);
  const src = fs.readFileSync(full, 'utf8');
  if (src.includes('Generated by scripts/build.mjs')) continue;
  let out = src
    .replace(/#[0-9a-fA-F]{6}\b/g, (m) => HEX[m.toLowerCase()] || m)
    .replace(/rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,/g, (m, r, g, b) => {
      const to = RGB[`${r},${g},${b}`];
      return to ? `rgba(${to},` : m;
    });
  if (out !== src) { fs.writeFileSync(full, out); changed++; }
}
console.log(`Rebranded colors in ${changed} pages`);
