#!/usr/bin/env node
// One-time rebrand of the hand-built pages: dark violet/cyan -> light editorial pink.
// Safe to re-run: no target color is also a source color.
//   node scripts/rebrand-legacy-colors.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SKIP = new Set(['email-template.html', 'card.html', 'google8dc333a5d1a3e4f3.html', 'index-v2-backup.html']);

// Solid colors (case-insensitive, whole hex only).
const HEX = {
  // dark surfaces -> light surfaces
  '#0c0a1a': '#faf8f4', '#110f24': '#f4f0ea', '#16132e': '#ffffff', '#1c1838': '#fdf2f7',
  // text on dark -> text on light
  '#f0eef8': '#17151f', '#c4c0d8': '#2d2a37', '#7a758f': '#615c6e',
  // violet / cyan / indigo accents -> pink
  '#7c3aed': '#be185d', '#a78bfa': '#be185d', '#c084fc': '#be185d', '#818cf8': '#be185d',
  '#06b6d4': '#db2777', '#22d3ee': '#be185d', '#2dd4bf': '#be185d',
  // light-on-dark status colors -> readable on light
  '#34d399': '#047857', '#10b981': '#047857', '#fbbf24': '#b45309', '#f59e0b': '#b45309',
  '#f87171': '#b91c1c', '#fb7185': '#be123c',
};
// rgba(r,g,b,a) channels -> new channels, alpha kept.
const RGB = {
  '12,10,26': '250,248,244', '17,15,36': '255,255,255', '22,19,46': '255,255,255', '28,24,56': '253,242,247', '15,12,35': '250,248,244',
  '255,255,255': '23,21,31',            // faint white lines on dark -> faint ink lines on light
  '122,117,143': '97,92,110',
  '124,58,237': '190,24,93', '167,139,250': '190,24,93', '168,85,247': '219,39,119', '59,130,246': '219,39,119',
  '6,182,212': '236,72,153', '34,211,238': '236,72,153', '45,212,191': '236,72,153', '13,148,136': '190,24,93',
  '52,211,153': '4,120,87', '16,185,129': '4,120,87', '251,191,36': '180,83,9', '245,158,11': '180,83,9',
};

let changed = 0;
for (const f of fs.readdirSync(ROOT).filter((f) => f.endsWith('.html') && !SKIP.has(f))) {
  const full = path.join(ROOT, f);
  const src = fs.readFileSync(full, 'utf8');
  if (src.includes('Generated by scripts/build.mjs')) continue;
  let out = src
    // wordmark "Sarah" was white on dark; make it ink
    .replace(/(<tspan fill=")#ffffff(">Sarah<\/tspan>)/gi, '$1#17151f$2')
    .replace(/#[0-9a-fA-F]{6}\b/g, (m) => HEX[m.toLowerCase()] || m)
    .replace(/rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,/g, (m, r, g, b) => {
      const to = RGB[`${r},${g},${b}`];
      return to ? `rgba(${to},` : m;
    });
  if (out !== src) { fs.writeFileSync(full, out); changed++; }
}
console.log(`Rebranded colors in ${changed} pages`);
